#!/usr/bin/env python3
# Generate src/unicode_bidi_gen.cpp — the Bidi_Class property, from the PINNED
# 18.0 extracted/DerivedBidiClass.txt.  Re-run: python3 tools/gen_unicode_bidi.py
import re

SRC = "tools/ucd/DerivedBidiClass-18.0.0.txt"
VER = "18.0.0"

# The file lists assigned code points (and the BN defaults); the rest take
# its `@missing` defaults, which are not all L: unassigned code points in the
# Hebrew, Arabic, Syriac, … blocks are R or AL, and in Currency Symbols ET.
# The lookup answers L for anything not here, so the other defaults are
# written out, under the data lines.
LONG = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL",
        "European_Terminator": "ET", "Boundary_Neutral": "BN"}
cls = {}     # code point -> class, for everything that is not plain L
data = []
for raw in open(SRC):
    m = re.match(r'# @missing: ([0-9A-Fa-f]+)\.\.([0-9A-Fa-f]+); (\w+)', raw)
    if m:
        lo, hi, v = int(m.group(1), 16), int(m.group(2), 16), LONG[m.group(3)]
        for cp in range(lo, hi + 1):
            if v == "L":
                cls.pop(cp, None)
            else:
                cls[cp] = v
        continue
    line = raw.split('#', 1)[0].strip()
    if not line:
        continue
    m = re.match(r'([0-9A-Fa-f]+)(?:\.\.([0-9A-Fa-f]+))?\s*;\s*([A-Za-z]+)', line)
    if not m:
        continue
    lo = int(m.group(1), 16)
    hi = int(m.group(2), 16) if m.group(2) else lo
    data.append((lo, hi, m.group(3)))
for lo, hi, v in data:
    for cp in range(lo, hi + 1):
        cls[cp] = v
ranges = []  # (lo, hi, BidiClass) e.g. "L", "EN", "WS"; L only where the file says so
for cp in sorted(cls):
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == cls[cp]:
        ranges[-1] = (ranges[-1][0], cp, cls[cp])
    else:
        ranges.append((cp, cp, cls[cp]))

with open("src/unicode_bidi_gen.cpp", "w") as f:
    f.write(f"// GENERATED by tools/gen_unicode_bidi.py from Unicode {VER} DerivedBidiClass.txt — do not edit.\n")
    f.write("#include <cstdint>\n#include <cstddef>\n")
    f.write("namespace rakupp { namespace ucd {\n")
    f.write("struct BidiEnt { uint32_t lo, hi; const char* bc; };\n")
    f.write("extern const BidiEnt BIDI[] = {\n")
    for lo, hi, bc in ranges:
        f.write(f'  {{0x{lo:X},0x{hi:X},"{bc}"}},\n')
    f.write("};\n")
    f.write(f"extern const size_t BIDI_N = {len(ranges)};\n")
    # The SLIM seam (src/ucd_seam.h)
    f.write("\n// The SLIM seam (src/ucd_seam.h) — see unicode_names.cpp for the note.\n")
    f.write("const BidiEnt* bidiTable(size_t* n) { *n = BIDI_N; return BIDI; }\n")
    f.write("}} // namespace rakupp::ucd\n")

print(f"emitted {len(ranges)} bidi ranges -> src/unicode_bidi_gen.cpp")
